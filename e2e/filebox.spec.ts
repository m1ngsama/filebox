function sha(p: string) {
  return new Promise<string>((resolve) => {
    const h = createHash('sha256')
    createReadStream(p).on('data', (d) => h.update(d)).on('end', () => resolve(h.digest('hex')))
  })
}

function bigFile(mb: number) {
  const p = join(tmpdir(), `filebox-e2e-${mb}.bin`)
  if (existsSync(p) && statSync(p).size === mb << 20) return p
  const fd = openSync(p, 'w')
  const buf = Buffer.alloc(1 << 20)
  for (let i = 0; i < mb; i++) {
    buf.fill(i % 251)
    buf.writeUInt32LE(i, 0)
    writeSync(fd, buf)
  }
  closeSync(fd)
  return p
}

function png(w: number, h: number) {
  const chunk = (type: string, data: Buffer) => {
    const b = Buffer.alloc(12 + data.length)
    b.writeUInt32BE(data.length, 0)
    b.write(type, 4)
    data.copy(b, 8)
    b.writeUInt32BE(crc32(b.subarray(4, 8 + data.length)), 8 + data.length)
    return b
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0)
  ihdr.writeUInt32BE(h, 4)
  ihdr[8] = 8
  const rows = Buffer.alloc((w + 1) * h, 0x80)
  for (let y = 0; y < h; y++) rows[y * (w + 1)] = 0
  return Buffer.concat([Buffer.from('89504e470d0a1a0a', 'hex'), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(rows)), chunk('IEND', Buffer.alloc(0))])
}

